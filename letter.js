const stage = document.getElementById('page-stage');
const indicator = document.getElementById('page-indicator');
let current = 0;

function renderInitial() {
  pages.forEach((text, i) => {
    const div = document.createElement('div');
    div.className = 'page' + (i === 0 ? ' active' : '');
    div.innerHTML = `<span class="page-number-tag">Halaman ${i + 1}</span><div class="page-body">${escapeHtml(text)}</div>`;
    stage.appendChild(div);
  });
  updateIndicator();
}

function escapeHtml(str) {
  const div = document.createElement('div');
  div.textContent = str;
  return div.innerHTML;
}

function updateIndicator() {
  indicator.textContent = `${current + 1} / ${pages.length}`;
  document.getElementById('flip-prev-btn').disabled = current === 0;
  document.getElementById('flip-next-btn').disabled = current === pages.length - 1;
}

function goTo(next) {
  if (next < 0 || next >= pages.length || next === current) return;
  const dir = next > current ? 'right' : 'left';
  const pageEls = stage.querySelectorAll('.page');
  const from = pageEls[current];
  const to = pageEls[next];

  from.classList.remove('active');
  from.classList.add(dir === 'right' ? 'leaving-left' : 'leaving-right');

  to.classList.remove('leaving-left', 'leaving-right');
  // force reflow so the transition plays from the correct starting transform
  void to.offsetWidth;
  to.classList.add('active');

  setTimeout(() => {
    from.classList.remove('leaving-left', 'leaving-right');
  }, 380);

  current = next;
  updateIndicator();
}

document.getElementById('flip-prev').addEventListener('click', () => goTo(current - 1));
document.getElementById('flip-next').addEventListener('click', () => goTo(current + 1));
document.getElementById('flip-prev-btn').addEventListener('click', () => goTo(current - 1));
document.getElementById('flip-next-btn').addEventListener('click', () => goTo(current + 1));

// ==== cover ====
const cover = document.getElementById('cover');
const book = document.getElementById('book');

cover.addEventListener('click', () => {
  cover.style.transition = 'opacity 0.4s ease, transform 0.4s ease';
  cover.style.opacity = '0';
  cover.style.transform = 'scale(0.96)';
  setTimeout(() => {
    cover.hidden = true;
    book.hidden = false;
  }, 380);
});

renderInitial();

